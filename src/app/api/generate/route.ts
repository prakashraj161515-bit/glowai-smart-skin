import { NextResponse } from "next/server";
import { GoogleGenerativeAI } from "@google/generative-ai";
import { getSecureKey } from "@/lib/api-key-manager";

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const apiKey = getSecureKey();

    if (!apiKey) return NextResponse.json({ error: "API key missing" }, { status: 500 });

    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ 
      model: "gemini-3.1-flash-lite-preview",
      generationConfig: { maxOutputTokens: 600, temperature: 0.4 }
    });

    let prompt = "";
    let imagePart: any = null;

    if (body.image) {
      // Extract base64 data and mime type
      const base64Data = body.image.split(",")[1];
      imagePart = {
        inlineData: {
          data: base64Data,
          mimeType: "image/jpeg"
        }
      };
    }

    if (body.mode === "product_scan") {
      prompt = `
        You are GlowAI, a world-class dermatological assistant. 
        Analyze the scanned skincare product image provided.
        
        STRUCTURE YOUR RESPONSE AS FOLLOWS:
        
        1. **PRODUCT OVERVIEW**
        Identify the product and briefly explain what it is.

        2. **USEFUL OR HARMFUL**
        Analyze the ingredients visible or typical for this product. State if it's safe or contains harsh chemicals.

        3. **WHY USE THIS?**
        Detail the specific benefits based on its ingredients.

        4. **WHO SHOULD AVOID THIS?**
        Mention skin types or conditions that should avoid this product.

        5. **MAIN PURPOSE**
        What is the core problem this product solves?

        MANDATORY RULES:
        - Use • for bullet points.
        - Use **HEADERS** in all caps.
        - END the report with the text: "Generated by GlowAI (AI Generated)".
        - If no product is visible, state "Please provide a clearer photo of the product label."
      `;
    } else if (body.message) {
      prompt = `
        You are GlowAI, a world-class dermatological assistant. 
        User Question: "${body.message}"
        Provide professional skincare advice. Keep it concise.
      `;
    } else {
      const { acne = 0, oil = 0, pigmentation = 0, score = 0, userName = "User" } = body;
      prompt = `
        Analyze this skin scan image for ${userName}.
        Metrics provided by local analysis:
        - Glow Score: ${score}/100
        - Acne Level: ${acne}%
        - Oiliness: ${oil}%
        - Pigmentation: ${pigmentation}%

        Provide a professional dermatological report with sections for DIET, MORNING ROUTINE, NIGHT ROUTINE, and PRO GLOW TIPS.
        Use • for bullet points.
      `;
    }

    const content = imagePart ? [prompt, imagePart] : [prompt];
    const result = await model.generateContent(content);
    const text = result.response.text();

    return NextResponse.json({ text });
  } catch (err: any) {
    console.error("🔥 Next.js AI Error:", err);
    return NextResponse.json({ error: "Failed to connect to AI" }, { status: 500 });
  }
}
